import { chromium } from '@playwright/test';
import { writeFile, mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
const output = resolve(process.cwd(), '../../output/verification/browser');
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const context = await browser.newContext({ viewport: { width: 390, height: 640 } });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const steps = [];
try {
  await page.goto('http://localhost:3100', { waitUntil: 'networkidle' });
  await page.getByRole('button', { name: 'Create a pot', exact: true }).first().click();
  await page.getByLabel('Deposit per person', { exact: true }).fill('1.0000001');
  await page.getByRole('button', { name: 'Review commitment', exact: true }).click();
  await page.locator('.notice.error').waitFor();
  if (await page.getByRole('button', { name: 'Confirm and create', exact: true }).count()) throw new Error('Invalid precision reached confirmation');
  steps.push('Exact token precision rejected before wallet request');
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  await page.getByRole('button', { name: 'Back', exact: true }).click();
  await page.getByRole('button', { name: 'Load a five-person example', exact: true }).last().click();
  await page.getByRole('heading', { name: 'Commitment pot #1' }).waitFor();
  await page.getByRole('button', { name: 'Move to next phase', exact: true }).click();
  await page.locator('.personal-panel select').selectOption('0x0000000000000000000000000000000000000006');
  await page.getByRole('button', { name: 'Check-in desk', exact: true }).click();
  await page.getByLabel('Participant QR contents', { exact: true }).fill('https://untrusted.example/');
  await page.getByRole('button', { name: 'Check participant', exact: true }).click();
  await page.locator('.notice.error').waitFor();
  if (await page.locator('.candidate').count()) throw new Error('Invalid QR became a participant');
  steps.push('Untrusted QR URL rejected without navigation or candidate');
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  const payload = JSON.stringify({ v: 1, potId: '1', participant: '0x0000000000000000000000000000000000000001' });
  await page.getByLabel('Participant QR contents', { exact: true }).fill(payload);
  await page.getByRole('button', { name: 'Check participant', exact: true }).click();
  if (await page.getByRole('button', { name: 'Sign and record attendance', exact: true }).isEnabled()) throw new Error('Attendance allowed without explicit attestation');
  steps.push('Explicit human-presence attestation required before signing');
  await page.getByRole('button', { name: 'VI', exact: true }).click();
  await page.getByRole('button', { name: 'Ký và ghi nhận điểm danh', exact: true }).waitFor();
  if (await page.getByLabel('Nội dung QR của người tham gia', { exact: true }).inputValue() !== payload) throw new Error('Locale switch reset scanned payload');
  steps.push('Language change preserves verifier candidate and scanned data');
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
  if (overflow) throw new Error('Low-height mobile horizontal overflow');
  steps.push('390×640 verifier layout remains within viewport width');
  if (errors.length) throw new Error(errors.join('; '));
  await writeFile(resolve(output, 'input-boundaries.json'), JSON.stringify({ status: 'passed', steps, errors, mockOnly: true, viewport: '390x640' }, null, 2));
  console.log(JSON.stringify({ status: 'passed', steps }));
} catch (error) {
  await page.screenshot({ path: resolve(output, 'input-failure.png'), fullPage: true });
  await writeFile(resolve(output, 'input-failure.json'), JSON.stringify({ steps, error: String(error), text: await page.locator('body').innerText(), url: page.url() }, null, 2));
  throw error;
} finally { await browser.close(); }
